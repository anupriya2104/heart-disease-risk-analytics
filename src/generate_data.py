"""
Synthetic survey data in the EXACT format of Kaggle "Personal Key Indicators of Heart Disease"
(heart_2020_cleaned.csv, CDC BRFSS 2020: 319,795 rows x 18 columns, ~8.6% HeartDisease = Yes).
Used only when data/raw/heart_2020_cleaned.csv is absent. Real data:
https://www.kaggle.com/datasets/kamilpytlak/personal-key-indicators-of-heart-disease

Risk factors are correlated the way they are in real populations (age -> worse general health,
BMI -> diabetes, smoking -> lung/kidney issues), so naive single-factor analysis is confounded.
"""
from pathlib import Path

import numpy as np
import pandas as pd

RNG = np.random.default_rng(2020)
OUT = Path(__file__).resolve().parents[1] / "data" / "raw"
N = 319_795

AGES = ["18-24", "25-29", "30-34", "35-39", "40-44", "45-49", "50-54", "55-59", "60-64", "65-69", "70-74", "75-79", "80 or older"]
AGE_P = np.array([6.6, 5.3, 5.9, 6.4, 6.6, 6.8, 7.9, 9.3, 10.5, 10.7, 9.7, 6.7, 7.6])
GEN = ["Excellent", "Very good", "Good", "Fair", "Poor"]
RACES = ["White", "Hispanic", "Black", "Other", "Asian", "American Indian/Alaskan Native"]
RACE_P = [0.767, 0.086, 0.072, 0.034, 0.025, 0.016]


def yn(mask):
    return np.where(mask, "Yes", "No")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    age_i = RNG.choice(len(AGES), N, p=AGE_P / AGE_P.sum())
    age = (age_i - 6) / 4.0  # ~ standardized age
    male = RNG.random(N) < 0.475
    race = RNG.choice(RACES, N, p=RACE_P)

    bmi = np.clip(RNG.lognormal(np.log(27.3) + 0.02 * age, 0.2, N), 12, 94).round(2)
    smoking = RNG.random(N) < 1 / (1 + np.exp(-(-0.45 + 0.12 * age + 0.2 * male)))
    alcohol = RNG.random(N) < 1 / (1 + np.exp(-(-2.6 - 0.15 * age + 0.2 * male)))
    phys_act = RNG.random(N) < 1 / (1 + np.exp(-(1.55 - 0.25 * age - 0.05 * (bmi - 27) - 0.3 * smoking)))
    diab_lin = -3.4 + 0.65 * age + 0.11 * (bmi - 27) - 0.3 * phys_act + 0.15 * male
    u = RNG.random(N)
    p_diab = 1 / (1 + np.exp(-diab_lin))
    diabetic = np.where(u < p_diab, "Yes", np.where(u < p_diab * 1.17, "No, borderline diabetes", "No")).astype(object)
    preg = (~male) & (age_i <= 5) & (RNG.random(N) < 0.025)
    diabetic[preg] = "Yes (during pregnancy)"
    asthma = RNG.random(N) < 1 / (1 + np.exp(-(-2.0 + 0.03 * (bmi - 27) + 0.2 * smoking - 0.25 * male)))
    kidney = RNG.random(N) < 1 / (1 + np.exp(-(-4.6 + 0.7 * age + 0.6 * (diabetic == "Yes"))))
    skin = RNG.random(N) < 1 / (1 + np.exp(-(-4.0 + 0.95 * age + 0.6 * (race == "White"))))
    stroke = RNG.random(N) < 1 / (1 + np.exp(-(-4.5 + 0.75 * age + 0.4 * smoking + 0.45 * (diabetic == "Yes"))))

    # general health: latent "health" driven by age, BMI, inactivity, smoking, chronic disease
    gh_lat = (0.45 * age + 0.06 * (bmi - 27) - 0.6 * phys_act + 0.35 * smoking + 0.9 * (diabetic == "Yes")
              + 0.9 * kidney + 0.9 * stroke + RNG.normal(0, 1, N))
    gen_i = np.digitize(gh_lat, [-1.15, 0.05, 1.15, 2.25])
    physical = np.clip(RNG.poisson(np.exp(-0.2 + 0.65 * gen_i)) * (RNG.random(N) < 0.18 + 0.15 * gen_i), 0, 30)
    mental = np.clip(RNG.poisson(np.exp(0.5 + 0.25 * gen_i - 0.2 * age)) * (RNG.random(N) < 0.3 + 0.05 * gen_i), 0, 30)
    diff_walk = RNG.random(N) < 1 / (1 + np.exp(-(-3.2 + 0.5 * age + 0.6 * gen_i + 0.04 * (bmi - 27))))
    sleep = np.clip(np.round(RNG.normal(7.1, 1.4, N) - 0.2 * (gen_i >= 3)), 1, 24)

    # outcome: log-odds with realistic effect sizes (BRFSS-like odds ratios)
    lin = (-4.43 + 1.0 * age + 0.70 * male + 0.55 * gen_i - 0.04 * gen_i ** 2 + 1.05 * stroke
           + 0.45 * (diabetic == "Yes") + 0.15 * (diabetic == "No, borderline diabetes") + 0.38 * smoking
           + 0.25 * diff_walk + 0.55 * kidney + 0.12 * asthma + 0.10 * skin - 0.25 * alcohol
           + 0.008 * (bmi - 27) + 0.012 * physical + 0.006 * mental - 0.04 * phys_act
           + 0.06 * (sleep - 7) ** 2 * (np.abs(sleep - 7) > 2)
           + 0.25 * (age > 1) * (diabetic == "Yes") + 0.3 * stroke * (diabetic == "Yes"))  # interactions
    hd = RNG.random(N) < 1 / (1 + np.exp(-lin))

    df = pd.DataFrame({
        "HeartDisease": yn(hd), "BMI": bmi, "Smoking": yn(smoking), "AlcoholDrinking": yn(alcohol),
        "Stroke": yn(stroke), "PhysicalHealth": physical.astype(float), "MentalHealth": mental.astype(float),
        "DiffWalking": yn(diff_walk), "Sex": np.where(male, "Male", "Female"), "AgeCategory": np.array(AGES)[age_i],
        "Race": race, "Diabetic": diabetic, "PhysicalActivity": yn(phys_act), "GenHealth": np.array(GEN)[gen_i],
        "SleepTime": sleep, "Asthma": yn(asthma), "KidneyDisease": yn(kidney), "SkinCancer": yn(skin),
    })
    df.to_csv(OUT / "heart_2020_cleaned.csv", index=False)
    (OUT / ".synthetic").write_text("generated by src/generate_data.py\n")
    print(f"heart_2020_cleaned.csv: {len(df):,} rows, prevalence {hd.mean():.2%}")


if __name__ == "__main__":
    main()
